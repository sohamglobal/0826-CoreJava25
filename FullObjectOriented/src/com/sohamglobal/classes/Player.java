package com.sohamglobal.classes;

public class Player {
	
	private String name;
	private int age;
	
	// To assign value -> set
	// To retrieve value -> get
	
	public void setName(String name)
	{
		this.name=name;
	}
	public void setAge(int a)
	{
		age=a;
	}
	
	public String getName()
	{
		return name;
	}
	public int getAge()
	{
		return age;
	}
	
	

}
